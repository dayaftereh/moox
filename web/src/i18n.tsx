const catalogs: Record<Locale, Catalog> = { en, de }
const STORAGE_KEY = 'moox.locale'

function detectLocale(): Locale {
  const stored = window.localStorage.getItem(STORAGE_KEY)
  if (stored === 'de' || stored === 'en') return stored
  for (const language of navigator.languages ?? [navigator.language]) {
    const normalized = language.toLowerCase()
    if (normalized.startsWith('de')) return 'de'
    if (normalized.startsWith('en')) return 'en'
  }
  return 'en'
}

export function translate(locale: Locale, key: TranslationKey, vars: TranslationVars = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}

type I18nValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: TranslationKey, vars?: TranslationVars) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectLocale())

  const setLocale = (next: Locale) => {
    window.localStorage.setItem(STORAGE_KEY, next)
    setLocaleState(next)
  }

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, vars) => translate(locale, key, vars),
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
